CALLS_OPEN = f"<{E.dsml_token}{E.tool_calls_block_name}>"
CALLS_CLOSE = f"</{E.dsml_token}{E.tool_calls_block_name}>"
INVOKE_OPEN = f"<{E.dsml_token}{E.tool_call_tag_name}"
INVOKE_CLOSE = f"</{E.dsml_token}{E.tool_call_tag_name}>"
P_OPEN = f"<{E.dsml_token}{E.tool_parameter_tag_name}"
P_CLOSE = f"</{E.dsml_token}{E.tool_parameter_tag_name}>"
PARAMETER = re.compile(re.escape(P_OPEN) + r' name="([^"]+)" string="(true|false)">(.*?)'
                       + re.escape(P_CLOSE), re.S)
EFFORT = {"none": 0, "off": 0, "disabled": 0, "false": 0, "minimal": 50, "low": 50,
          "medium": 62, "high": 75, "xhigh": 75, "max": 100, "maximum": 100}


def effort_kwargs(value):
    if value is None or value == "":
        return {}
    key = str(value).strip().lower()
    if value is False:
        level = 0
    elif key.isdigit() and 0 <= int(key) <= 100:
        level = int(key)
    elif key in EFFORT:
        level = EFFORT[key]
    else:
        raise ValueError("reasoning_effort must be none, low, medium, high, max, or 1-100")
    return {"enable_thinking": False} if level == 0 else {"reasoning_effort": level}


def budget_effort(tokens):
    n = int(tokens)
    return {"reasoning_effort": 50 if n < 2048 else 62 if n < 8192 else 75}


def text_content(content):
    if content is None or isinstance(content, str):
        return content or ""
    if not isinstance(content, list):
        raise ValueError("content must be text or a list of text blocks")
    if any(not isinstance(p, dict) or p.get("type") not in ("text", "input_text", None)
           for p in content):
        raise ValueError("DeepSeek V4.1 adapter supports text only (no image/audio/video input)")
    return "".join(p.get("text", "") for p in content)


def to_encoder_messages(messages, tools=None):
    out = []
    for msg in messages:
        msg = dict(msg, content=text_content(msg.get("content")))
        if msg.get("tool_calls"):
            msg["tool_calls"] = [
                dict(c, type="function", function=dict(c.get("function") or {}, arguments=(
                    c.get("function", {}).get("arguments", "{}"))))
                for c in msg["tool_calls"]]
        out.append(msg)
    if tools:
        wrapped = [t if "function" in t else {"type": "function", "function": t} for t in tools]
        if out and out[0]["role"] == "system":
            out[0] = dict(out[0], tools=wrapped)
        else:
            out.insert(0, {"role": "system", "content": "", "tools": wrapped})
    return out


class Ds41Template:
    source = "{# DeepSeek V4.1: dsv41_encoding.encode_messages, not Jinja #}"
    caps = {"supports_tools": True, "supports_tool_calls": True, "supports_system_role": True,
            "supports_parallel_tool_calls": True, "supports_preserve_reasoning": False}

    def __init__(self, path=None):
        pass

    def render(self, messages, tools=None, add_generation_prompt=True, **kwargs):
        effort = effort_kwargs(kwargs.get("reasoning_effort"))
        mode = "chat" if kwargs.get("enable_thinking") is False or effort.get("enable_thinking") is False else "thinking"
        prompt = E.encode_messages(to_encoder_messages(messages, tools), thinking_mode=mode,
                                   reasoning_effort=effort.get("reasoning_effort"))
        if not add_generation_prompt:
            suffix = E.ASSISTANT_SP_TOKEN + (
                E.thinking_start_token if mode == "thinking" else E.thinking_end_token)
            if prompt.endswith(suffix):
                prompt = prompt[:-len(suffix)]
        return prompt


def unescape(value):
    tail = P_CLOSE[1:]
    return re.sub(r"&((?:amp;)*)lt;" + re.escape(tail),
                  lambda m: ("&" + m[1][:-4] + "lt;" if m[1] else "<") + tail, value)


def parse_tool_call(body):
    match = re.match(r'\s*name="([^"]+)">\s*', body)
    if not match:
        raise ValueError("malformed DSML invoke")
    args, pos = {}, match.end()
    for parameter in PARAMETER.finditer(body, pos):
        if body[pos:parameter.start()].strip() or parameter[1] in args:
            raise ValueError("malformed or duplicate DSML parameter")
        value = unescape(parameter[3])
        args[parameter[1]] = value if parameter[2] == "true" else json.loads(value)
        pos = parameter.end()
    if body[pos:].strip():
        raise ValueError("malformed DSML parameters")
    return F.ToolCall(name=match[1], arguments=args)


class Ds41OutputParser:
    """Stream text/reasoning; buffer each DSML invoke until its arguments are complete."""
    def __init__(self, thinking=True, tools=None, stream_tools=False, recover=False):
        self.state = "reasoning" if thinking else "content"
        self.buf = ""
        self.pending = []
        self.rescued = self.refused = 0
        self._calls = False
        self.names = {t.get("name") for t in tools or []}

    @staticmethod
    def _hold(text, tags):
        return max((n for tag in tags for n in range(1, min(len(tag), len(text) + 1))
                    if text.endswith(tag[:n])), default=0)

    def feed(self, delta):
        self.buf += delta
        out = []
        while self.buf:
            if self.state == "call":
                end = self.buf.find(INVOKE_CLOSE)
                if end < 0:
                    break
                call = parse_tool_call(self.buf[:end])
                if call.name in self.names:
                    out.append(F.Event("tool_call", call=call))
                else:
                    out.append(F.Event("content", INVOKE_OPEN + self.buf[:end] + INVOKE_CLOSE))
                self.buf = self.buf[end + len(INVOKE_CLOSE):]
                self.state = "content"
                continue
            tags = (E.thinking_end_token,) if self.state == "reasoning" else (
                CALLS_OPEN, CALLS_CLOSE, INVOKE_OPEN)
            hits = [(self.buf.find(tag), tag) for tag in tags if tag in self.buf]
            if hits:
                pos, tag = min(hits)
                if pos and not (self._calls and not self.buf[:pos].strip()):
                    out.append(F.Event(self.state, self.buf[:pos]))
                self.buf = self.buf[pos + len(tag):]
                if tag == E.thinking_end_token:
                    self.state = "content"
                elif tag == INVOKE_OPEN:
                    self.state = "call"
                else:
                    self._calls = tag == CALLS_OPEN
                continue
            held = self._hold(self.buf, tags)
            text = self.buf[:-held] if held else self.buf
            self.buf = self.buf[-held:] if held else ""
            if text and not (self._calls and not text.strip()):
                out.append(F.Event(self.state, text))
            break
        return out

    def finish(self, reason=None):
        if not self.buf:
            return []
        # Never turn a truncated tool call into an executable action.
        text = (INVOKE_OPEN if self.state == "call" else "") + self.buf
        kind = "reasoning" if self.state == "reasoning" else "content"
        self.buf = ""
        return [F.Event(kind, text)]


def forced_call(choice, tools):
    kind, name = F.tool_choice_of(choice)
    if kind in ("auto", "none"):
        return None
    raise ValueError("DeepSeek V4.1 adapter supports tool_choice auto/none, not forced tool calls")


_openai_to_messages = F.openai_to_messages
_anthropic_to_messages = F.anthropic_to_messages


def check_native_sampling(req):
    for key, default in (("presence_penalty", 0), ("frequency_penalty", 0),
                         ("repetition_penalty", 1), ("repeat_penalty", 1)):
        if req.get(key) not in (None, default):
            raise ValueError(f"{key} is not implemented by ds41_generate")
    if req.get("logit_bias") or req.get("strata_tune"):
        raise ValueError("logit_bias and strata_tune are not implemented by ds41_generate")


def sampling_keys(sampling):
    check_native_sampling(sampling)
    return "".join(f" {key}={float(value)!r}" if key in ("temperature", "top_p", "min_p")
                   else f" {key}={int(value)}"
                   for key in ("temperature", "top_p", "top_k", "min_p", "seed")
                   if (value := sampling.get(key)) is not None)


def openai_to_messages(req):
    check_native_sampling(req)
    messages, tools, kwargs = _openai_to_messages(req)
    # The Qwen conversion does not need call IDs. DeepSeek uses them to sort parallel tool results.
    for out, raw in zip(messages, req.get("messages") or []):
        if "tool_call_id" in raw:
            out["tool_call_id"] = raw["tool_call_id"]
        for call, original in zip(out.get("tool_calls", []), raw.get("tool_calls", [])):
            for name in ("id", "namespace"):
                if name in original:
                    call[name] = original[name]
    return messages, tools, kwargs


def anthropic_to_messages(req, think_unasked=True):
    check_native_sampling(req)
    messages, tools, kwargs = _anthropic_to_messages(req, think_unasked)
    calls, results = [], []
    for message in req.get("messages") or []:
        blocks = message.get("content")
        if not isinstance(blocks, list):
            continue
        for block in blocks:
            if block.get("type") == "tool_use":
                calls.append(block.get("id"))
            elif block.get("type") == "tool_result":
                results.append(block.get("tool_use_id"))
    calls, results = iter(calls), iter(results)
    for message in messages:
        if message["role"] == "tool":
            message["tool_call_id"] = next(results, None)
        for call in message.get("tool_calls", []):
            call["id"] = next(calls, None)
    return messages, tools, kwargs


_installed = False


def install_adapter():
    """Install only on the explicitly selected V4.1 server process."""
    global _installed
    if _installed:
        return
    _installed = True
    import strata_tokenizer
    strata_tokenizer.Tokenizer = Ds41Tokenizer
    F.effort_kwargs = effort_kwargs
    F.budget_effort = budget_effort
    F._late_system_to_user = lambda messages: messages
    F._env_to_user = lambda messages: messages
    S.ChatTemplate = Ds41Template
    S.OutputParser = Ds41OutputParser
    S.forced_call = forced_call
    S.openai_to_messages = openai_to_messages
    S.anthropic_to_messages = anthropic_to_messages
    S.IM_END = E.eos_token
    original_init = S.Service.__init__

    def init(self, engine, tokenizer, template, *args, **kwargs):
        original_init(self, engine, tokenizer, template, *args, **kwargs)
        eos = tokenizer.encode(E.eos_token, parse_special=True)
        if len(eos) != 1:
            raise ValueError("V4.1 tokenizer must encode EOS as one token; export its tokenizer first")
        self.stop_ids = set(eos)
        self.effort_end = False

    S.Service.__init__ = init
    # The source engine has no Qwen effort-tail/session/batch flags. Keep its argument list literal.
    S.engine_args = lambda cfg: list(cfg["args"])
    S.StrataEngine.sampling_keys = staticmethod(sampling_keys)
    S.effort_end_args = lambda *args: None
    S.layer_split_of = lambda cfg: False


def validate_binding(host, key):
    try:
        local = ipaddress.ip_address(host).is_loopback
    except ValueError:
        local = host.lower() == "localhost"
    if not local and not S.api_key_of(key):
        raise ValueError("non-local binding requires --api-key or STRATA_API_KEY")


def main():
    ap = argparse.ArgumentParser(add_help=False)
    ap.add_argument("--config")
    ap.add_argument("--host")
    ap.add_argument("--api-key")
    ap.add_argument("--engine")
    ap.add_argument("--tokenizer")
    args, _ = ap.parse_known_args()
    cfg = S.read_config(args.config) if args.config else {}
    try:
        validate_binding(args.host or cfg.get("host") or "127.0.0.1",
                         args.api_key or os.environ.get("STRATA_API_KEY") or cfg.get("api_key"))
        for name in ("vision", "images", "parallel", "replicas", "effort_position",
                     "reasoning_close_retry", "reasoning_loop_recovery", "tool_call_recovery"):
            if cfg.get(name):
                raise ValueError(f"{name} is not supported by the V4.1 adapter")
        if args.engine == "strata" and not cfg.get("env", {}).get("STRATA_V41_CONFIG") and not os.environ.get("STRATA_V41_CONFIG"):
            raise ValueError("standard 1017 GGUF requires STRATA_V41_CONFIG; use launch.py")
    except ValueError as exc:
        raise SystemExit(str(exc)) from exc
    install_adapter()
    return S.main()


if __name__ == "__main__":
    sys.exit(main())
