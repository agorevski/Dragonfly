"""Opt-in DeepSeek V4.1 adapter for this checkout's OpenAI/Anthropic HTTP server.

Run with --engine strata --config SERVER_CONFIG.json (generated by launch.py).
Only this process installs the adapter; importing it does not change core classes.
Text, reasoning and DSML tools are supported. Vision is not wired to this engine.
Forced tool choice, batch/replica/session features and incremental tool
argument deltas are not implemented. Each completed tool call is sent atomically.
Native sampling supports temperature, top_p, top_k, min_p and seed, not penalties
or logit bias. Core HTTP endpoints do not imply native support for those features.
"""
